"""Canonical ExtractionResult domain value object."""

from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum
from typing import Any
from uuid import UUID

from app.domain.value_objects.classification_result import ConfidenceLevel
from app.domain.value_objects.document_type import DocumentType
from app.domain.value_objects.provenance import Provenance


class ExtractionStatus(str, Enum):
    """Execution status for artifact entity extraction."""

    SUCCESS = "SUCCESS"
    PARTIAL = "PARTIAL"
    FAILED = "FAILED"
    NOT_SUPPORTED = "NOT_SUPPORTED"
    SKIPPED = "SKIPPED"


@dataclass(frozen=True)
class ExtractionResult:
    """Immutable domain value object representing the canonical outcome of artifact entity extraction."""

    artifact_id: UUID
    document_type: DocumentType
    structured_data: dict[str, Any] = field(default_factory=dict)
    provenance: dict[str, Provenance] = field(default_factory=dict)
    warnings: list[str] = field(default_factory=list)
    confidence: ConfidenceLevel = ConfidenceLevel.LOW
    extractor_version: str = "1.0.0"
    prompt_version: str = "v1"
    llm_metadata: dict[str, Any] = field(default_factory=dict)
    started_at: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    completed_at: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    status: ExtractionStatus = ExtractionStatus.SUCCESS
    error_message: str | None = None

    @property
    def is_placeholder(self) -> bool:
        """Returns True if this extraction result was generated by a placeholder."""
        return bool(self.llm_metadata.get("is_placeholder", False))

    @property
    def message(self) -> str:
        """Returns message detail if present in llm_metadata or error_message."""
        return str(self.llm_metadata.get("message", self.error_message or ""))

    @property
    def extractor_name(self) -> str:
        """Returns extractor version name string."""
        return self.extractor_version

    @property
    def extracted_data(self) -> dict[str, Any]:
        """Alias for structured_data for backward compatibility."""
        return self.structured_data

    def to_dict(self) -> dict[str, Any]:
        """Serializes extraction result for transport and persistence."""
        return {
            "artifact_id": str(self.artifact_id),
            "document_type": self.document_type.value,
            "structured_data": self.structured_data,
            "provenance": {k: v.to_dict() for k, v in self.provenance.items()},
            "warnings": self.warnings,
            "confidence": self.confidence.value,
            "extractor_version": self.extractor_version,
            "prompt_version": self.prompt_version,
            "llm_metadata": self.llm_metadata,
            "started_at": self.started_at.isoformat(),
            "completed_at": self.completed_at.isoformat(),
            "status": self.status.value,
            "error_message": self.error_message,
        }
